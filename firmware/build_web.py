#!/usr/bin/env python3
"""Pack firmware/hydra_web/web/index.html into hydra_web/web_page.h (gzip, PROGMEM).

Run after editing the page:   python3 firmware/build_web.py
The logo (assets/logo_64.png) is inlined as a data URI where the page says {{LOGO}}.
"""
import base64
import gzip
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE / 'hydra_web' / 'web' / 'index.html'
DST = HERE / 'hydra_web' / 'web_page.h'
LOGO = HERE.parent / 'assets' / 'logo_64.png'


def main():
    html = SRC.read_text(encoding='utf-8')
    if '{{LOGO}}' in html:
        uri = 'data:image/png;base64,' + base64.b64encode(LOGO.read_bytes()).decode()
        html = html.replace('{{LOGO}}', uri)
    data = gzip.compress(html.encode('utf-8'), compresslevel=9, mtime=0)
    lines = []
    for i in range(0, len(data), 20):
        lines.append('  ' + ', '.join(f'0x{b:02x}' for b in data[i:i + 20]) + ',')
    DST.write_text(
        '// Generated by firmware/build_web.py from web/index.html -- do not edit.\n'
        '#pragma once\n#include <pgmspace.h>\n\n'
        f'#define WEB_PAGE_GZ_LEN {len(data)}\n'
        'const uint8_t WEB_PAGE_GZ[] PROGMEM = {\n' + '\n'.join(lines) + '\n};\n',
        encoding='utf-8')
    print(f'{SRC.name}: {len(html.encode())} bytes -> {DST.name}: {len(data)} bytes gzip')


if __name__ == '__main__':
    main()
