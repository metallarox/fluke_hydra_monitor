#!/usr/bin/env python3
"""Pack the pages in firmware/hydra_web/web/ into hydra_web/web_page.h (gzip, PROGMEM).

index.html -> WEB_PAGE_GZ (served at /), debug.html -> DEBUG_PAGE_GZ (served at /debug).

Run after editing the page:   python3 firmware/build_web.py
The logo (assets/logo_64.png) is inlined as a data URI where the page says {{LOGO}}.
"""
import base64
import gzip
from pathlib import Path

HERE = Path(__file__).resolve().parent
WEB = HERE / 'hydra_web' / 'web'
PAGES = (('index.html', 'WEB_PAGE_GZ'), ('debug.html', 'DEBUG_PAGE_GZ'))
DST = HERE / 'hydra_web' / 'web_page.h'
LOGO = HERE.parent / 'assets' / 'logo_64.png'


def pack(path, name):
    html = path.read_text(encoding='utf-8')
    if '{{LOGO}}' in html:
        uri = 'data:image/png;base64,' + base64.b64encode(LOGO.read_bytes()).decode()
        html = html.replace('{{LOGO}}', uri)
    data = gzip.compress(html.encode('utf-8'), compresslevel=9, mtime=0)
    lines = ['  ' + ', '.join(f'0x{b:02x}' for b in data[i:i + 20]) + ',' for i in range(0, len(data), 20)]
    print(f'{path.name}: {len(html.encode())} bytes -> {name}: {len(data)} bytes gzip')
    return (f'#define {name}_LEN {len(data)}\n'
            f'const uint8_t {name}[] PROGMEM = {{\n' + '\n'.join(lines) + '\n};\n')


def main():
    body = '\n'.join(pack(WEB / fname, name) for fname, name in PAGES)
    DST.write_text('// Generated by firmware/build_web.py from web/*.html -- do not edit.\n'
                   '#pragma once\n#include <pgmspace.h>\n\n' + body, encoding='utf-8')


if __name__ == '__main__':
    main()
